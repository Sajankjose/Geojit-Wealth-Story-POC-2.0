import {test} from 'node:test'
import assert from 'node:assert/strict'
import {STORY_PEOPLE,SERVICE_DEMO,composeWealthStory,storyInsightOrder,storyPreference} from '../src/lib/wealthStoryOrchestrator.js'
import {fictionalFinancialInput,fixtureIntelligence} from '../src/lib/wealthIntelligence.js'
test('four fictional personas each receive a distinct contextual story',()=>{
 assert.deepEqual(STORY_PEOPLE.map(x=>x.id),['C012','C014','C008','C001'])
 const stories=STORY_PEOPLE.map(x=>composeWealthStory(x.id))
 assert.ok(stories.every(x=>x?.synthetic&&x.preview_only))
 assert.equal(new Set(stories.map(x=>x.headline)).size,4)
 assert.ok(stories.every(x=>x.next.product===false))
 assert.ok(stories.every(x=>x.verified_assigned_rm===false))
 assert.ok(stories.every(x=>x.can_submit_service_request===false))
})
test('Thomas insight reconciles exactly against the financial fixture, no inferred gains',()=>{
 const x=composeWealthStory('C012')
 const raw=fictionalFinancialInput('C012'),model=fixtureIntelligence('C012')
 const difference=raw.valuations.at(-1)-raw.valuations.at(-2)-raw.external_net_flows.at(-1)
 assert.equal(raw.external_net_flows.at(-1),3000)
 assert.equal(x.model.value_numeric,542000)
 assert.equal(x.model.value_numeric,model.value_numeric)
 assert.ok(x.signal.headline.includes('₹3,000'))
 assert.ok(x.signal.description.includes('₹'+Math.abs(difference).toLocaleString('en-IN')))
 assert.match(x.signal.source,/C012/i)
 assert.deepEqual(storyInsightOrder(x),['financial','insight','next','contact','feedback'])
})
test('George only sees explicitly declared goal and no false goal funding ratio',()=>{
 const x=composeWealthStory('C014')
 assert.equal(x.model.value_numeric,968000)
 assert.equal(x.model.goal.target,1500000)
 assert.equal(x.signal.type,'goal')
 assert.match(x.signal.description,/do not show how much/i)
 assert.match(x.signal.evidence.join(' '),/No goal-to-holding earmarking/i)
 assert.equal(x.next.topic,'goal')
})
test('Meera fictional service case leads, no fake RM or update promise',()=>{
 const x=composeWealthStory('C008')
 assert.deepEqual(x.service,SERVICE_DEMO)
 assert.equal(x.service.synthetic,true)
 assert.equal(x.service.status,'In progress')
 assert.equal(x.service.next_update,null)
 assert.equal(x.contact.verified,false)
 assert.equal(x.service.contact.assigned,false)
 assert.equal(x.service.contact.contact_verified,false)
 assert.match(x.service.note,/invented/i)
 assert.equal(storyInsightOrder(x)[0],'service')
 assert.equal(x.next.topic,'service')
})
test('Arun new customer gets no portfolio, financial returns or inferred wealth goal',()=>{
 const x=composeWealthStory('C001')
 assert.equal(x.model,null)
 assert.equal(x.signal.type,'new')
 assert.equal(x.next.topic,'learning')
 assert.match(x.signal.description,/unknown/i)
 assert.deepEqual(storyInsightOrder(x),['insight','next','learning','contact','feedback'])
})
test('invalid client ids cannot expose a story and preferences are allowlisted',()=>{
 assert.equal(composeWealthStory('C099'),null)
 assert.equal(composeWealthStory('a-real-client'),null)
 assert.equal(storyPreference('goals'),'goals')
 assert.equal(storyPreference('malicious_value'),'investments')
})
